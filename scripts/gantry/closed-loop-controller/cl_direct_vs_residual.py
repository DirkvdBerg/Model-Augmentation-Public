print('\n' + '=' * 104)
print('T3  PRECISION: the same comparison in float32 and float64')
print('=' * 104)
print('  building float64 pipeline ...', flush=True)
c64, fs64, n64, K64, na4, nb4, nar4, nbr4, step64, out64, bank64, nx64 = build(True)
set_ann_gain(fs64, GROWTH_GAIN)
sig64 = signals(c64, n64, K64, N_LONG)
ystd64 = np.asarray(n64.ystd).ravel()
row64 = bank64.rec_to_ctrl[0].item()
ctrl64 = tuple(bank64.__getattr__(k)[row64].numpy().astype(float) for k in 'ABCD')
