ucons64 = ufb64 + sig64['f']
yn64 = ((sig64['y'] - np.asarray(n64.y0).ravel()) / ystd64).astype(c64.dtype_np)
un64 = PLANT.normalise_u(ucons64, n64, c64.dtype_np)
N64 = sig64['N']

HORIZONS = [100, 1000, 10000]
print('  %-10s %-18s %-18s %-14s' % ('horizon', 'float32 gap [m]', 'float64 gap [m]', 'ratio'))
for H in HORIZONS:
    H32 = min(H, len(gap) - 1)
    g32 = float(np.max(gap[:H32 + 1]))
    x064 = CV.encoder_x0(fs64.encoder, un64, yn64, K64, na4, nb4, nar4, nbr4, c64.dtype_pt)
    end = min(K64 + H + 1, N64)
    ut = torch.as_tensor(np.ascontiguousarray(un64[None, K64:end]), dtype=c64.dtype_pt)
    yt = torch.as_tensor(np.ascontiguousarray(yn64[None, K64:end]), dtype=c64.dtype_pt)
    with torch.no_grad():
        yr64, _, _ = rollout(step64, out64, ut, yt, x064, bank64, ctrl_t64)
    yd64 = direct_rollout(step64, out64, sig64['r'][K64:end], sig64['f'][K64:end], x064,
                          xcD64[K64], ctrl64, n64, c64.dtype_pt)
    g64 = float(np.max(np.abs(yd64 - yr64[0].numpy()) * ystd64))
    print('  %-10d %-18.3e %-18.3e %-14.3g' % (H, g32, g64, g32 / max(g64, 1e-300)))
print('  An ALGEBRA error is precision-blind (ratio ~ 1). Float noise scales with eps (~1e8-1e9).')

# =============================================================================================
print('\n' + '=' * 104)
print('T4  TRAINING GEOMETRY: horizon nf = %d, the window the loss actually uses' % cfg.nf)
print('=' * 104)
starts = np.linspace(K0, N - cfg.nf - 2, N_WINDOWS).astype(int)
print('  %-8s %-16s %-16s %-10s' % ('ANN', 'max gap [m]', 'model err [m]', 'gap/err'))
for gain in ANN_GAINS:
    set_ann_gain(fs, gain)
    gaps, errs = [], []
    for s in starts:
        x0w = CV.encoder_x0(fs.encoder, un, yn, int(s), na, nb, na_r, nb_r, cfg.dtype_pt)
        uw = torch.as_tensor(np.ascontiguousarray(un[None, s:s + cfg.nf]), dtype=cfg.dtype_pt)
        yw = torch.as_tensor(np.ascontiguousarray(yn[None, s:s + cfg.nf]), dtype=cfg.dtype_pt)
        with torch.no_grad():
            yr, _, _ = rollout(step_fn, out_fn, uw, yw, x0w, bank, ctrl_t)
        yr = yr[0].numpy()
        yd = direct_rollout(step_fn, out_fn, sig['r'][s:s + cfg.nf], sig['f'][s:s + cfg.nf],
                            x0w, xc_D[s], ctrl_np, norm, cfg.dtype_pt)
        gaps.append(np.max(np.abs(yd - yr) * ystd))
        errs.append(np.sqrt(np.mean(((yr - yn[s:s + cfg.nf]) * ystd) ** 2)))
    gmax, emax = float(np.max(gaps)), float(np.mean(errs))
    print('  %-8.3g %-16.3e %-16.3e %-10.3e' % (gain, gmax, emax, gmax / max(emax, 1e-30)))

set_ann_gain(fs, 0.0)
print('\n[%.0fs]' % (time.time() - t0))
