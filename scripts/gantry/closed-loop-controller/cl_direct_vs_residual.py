"""Is the controller subtraction valid when the model is NONLINEAR?

THE OBJECTION
-------------
"You train in closed loop, the plant is LPV and the ANN correction is nonlinear, so you cannot
just subtract the difference in the controller output."

THE CLAIM
---------
    u_d = Cfb(r - y_d) + f_ms          machine loop
    u_m = Cfb(r - y_m) + f_ms          same controller around the model
    ------------------------------------------------------------------- subtract
    u_m = u_d + Cfb(y_d - y_m)                                          RESIDUAL FORM

Define the machine-loop DEFECT at the rate the training loop runs at,

    delta[k] := u_d[k] - ( Cfb(r - y_d)[k] + f_ms[k] )

Then for ANY model, linear or not, e_direct = (r - y_m) = (r - y_d) + (y_d - y_m) and linearity
of Cfb alone give

    u_direct[k] - u_residual[k] = delta[k]                                            (*)

i.e. the gap between the two forms is a MODEL-INDEPENDENT signal fixed by the data and the
controller. The nonlinearity lives in f, which the derivation never touches.

WHAT VERSION 1 OF THIS SCRIPT GOT WRONG
---------------------------------------
It compared 20000-step rollouts and found the two forms agreeing to 4.6e-9 m with the ANN off but
disagreeing at 7e-4 m, comparable to the model error itself, with the ANN on. That does NOT
distinguish the two candidate causes:

  (i)  the algebra is wrong, so the gap is O(model error) from the first step;
  (ii) the algebra is exact but the two arms are different floating-point programs, and a strongly
       nonlinear closed loop amplifies the eps-level difference exponentially over 20000 steps.

A single end-of-rollout number cannot tell those apart. This version separates them with four
measurements, of which T2, T3 and T4 are the discriminating ones.

  T1  ONE STEP, arbitrary states. Both forms evaluated at random model states and random
      controller states. No accumulation at all, so this is the algebraic identity on its own.
      Cause (i) fails here; cause (ii) cannot appear here.
  T2  GROWTH CURVE. |y_direct - y_residual| as a function of step index, next to a CONTROL: the
      residual form re-run from an x0 perturbed by one float32 eps. If the direct-vs-residual gap
      tracks the control curve, the gap IS numerical noise being amplified, and the amplification
      is a property of the model, not of the loop form.
  T3  PRECISION. The same experiment in float32 and in float64. Cause (i) is precision-blind;
      cause (ii) must drop by orders of magnitude.
  T4  TRAINING GEOMETRY. The horizon that actually matters is nf, the training window, not 20000
      steps. Reported over many windows.

TWO CONDITIONS FOR (*), TESTED NOT ASSUMED
------------------------------------------
  C1  both loops apply the SAME operator Cfb. True here: Cfb is built at the record's frozen Y_op,
      read from the record, so it is exogenous. A controller scheduled on the MODEL's own state
      would break this while still being linear, which is the failure mode worth naming.
  C2  consistent controller states, xc_direct = xc_D + xc_residual. The residual arm starts at
      xc_residual = 0, so the direct arm starts from the machine's reconstructed xc_D, obtained by
      filtering (r - y_d) from k = 0. Zeroing both would smuggle the SEPARATE xc = 0 approximation
      into a test that is not about it.

delta != 0 for these records, because they were generated by a 20 kHz controller while the
training loop runs at 4 kHz with Cfb re-discretised (D-141). Every arm below therefore uses
u_data := Cfb(r - y_d) + f_ms, the input CONSISTENT with the training-rate controller, so delta
is zero by construction and the algebra is isolated. The size of delta is reported separately.

Usage
-----
  PYTHONUNBUFFERED=1 python -u cl_direct_vs_residual.py
"""
