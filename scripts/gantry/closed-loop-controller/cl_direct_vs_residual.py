def build(use_f64):
    cfg = dataclasses.replace(CFG, seed=0, use_f64=use_f64)
    fs, norm, K0, na, nb, na_r, nb_r = dm.build_pipeline(cfg=cfg, verbose=False)
    nx = cfg.nx_phys + cfg.nx_ann
    C_out, b_out = PLANT.identify_output_map(fs.hfn, nx, cfg.nu, dtype=cfg.dtype_pt)
    step_fn, out_fn = PLANT.make_fns(fs, C_out, b_out)
    bank = ControllerBank([RECORD], cfg.ts_new, dtype=cfg.dtype_pt,
                          ystd=norm.ystd, std_u=norm.std_u)
    return cfg, fs, norm, K0, na, nb, na_r, nb_r, step_fn, out_fn, bank, nx


def signals(cfg, norm, K0, n_need):
    """Record signals at the TRAINING rate, plus the consistent input and the machine xc."""
    d = loadmat(os.path.join(traj_dir(cfg), RECORD + '.mat'), squeeze_me=True)
    D = cfg.d
    u_raw = _resample_u(np.asarray(d['u_total'], float), cfg)
    f_raw = _resample_u(np.asarray(d['f_sim'], float), cfg)
    N = min(len(u_raw), len(f_raw), K0 + n_need)
    return dict(N=N, u=u_raw[:N], f=f_raw[:N],
                r=np.asarray(d['r_sim'], float)[::D][:N],
                y=np.asarray(d['y'], float)[::D][:N])


print('=' * 104)
print('DIRECT vs RESIDUAL closed-loop form, with a NONLINEAR augmented model')
print('=' * 104)
print('building float32 pipeline ...', flush=True)
cfg, fs, norm, K0, na, nb, na_r, nb_r, step_fn, out_fn, bank, nx = build(False)
print('training rate %d Hz, decimation %d, dtype %s, nf = %d'
      % (cfg.fs_new_hz, cfg.d, cfg.dtype_np.__name__, cfg.nf))
ft = PLANT.check_no_feedthrough(fs.hfn, nx, cfg.nu, dtype=cfg.dtype_pt)
print('D_d = 0 check: %.3e   %s' % (ft, 'OK' if ft == 0.0 else 'NONZERO'))

sig = signals(cfg, norm, K0, N_LONG)
N = sig['N']
ystd = np.asarray(norm.ystd).ravel()
row = bank.rec_to_ctrl[0].item()
ctrl_np = tuple(bank.__getattr__(k)[row].numpy().astype(float) for k in 'ABCD')
ctrl_t = bank.gather(torch.tensor([0], dtype=torch.long))

u_fb_D, xc_D = machine_controller(sig['r'], sig['y'], ctrl_np)
u_cons = u_fb_D + sig['f']
delta = sig['u'] - u_cons
print('\n%s  Y_op %+.2f m' % (RECORD, y_op_for(RECORD)))
print(line('rms u_fb from (r - y_d) [N]', rms(u_fb_D)))
print(line('rms delta = u_total - (u_fb + f_ms) [N]', rms(delta)))
print(line('delta / u_fb  (the 20k->4k gap)', rms(delta) / rms(u_fb_D), '%9.5f'))
print('    every arm below uses u_data := u_fb + f_ms, so delta = 0 by construction')

yn = ((sig['y'] - np.asarray(norm.y0).ravel()) / ystd).astype(cfg.dtype_np)
un = PLANT.normalise_u(u_cons, norm, cfg.dtype_np)

# =============================================================================================
print('\n' + '=' * 104)
print('T1  ONE STEP, arbitrary model states and arbitrary controller states (no accumulation)')
print('=' * 104)
Ac, Bc, Cc, Dc = ctrl_np
u_mean = np.asarray(norm.u_mean).ravel()
std_u = np.asarray(norm.std_u).ravel()
y0v = np.asarray(norm.y0).ravel()

for gain in ANN_GAINS:
    set_ann_gain(fs, gain)
    g = torch.Generator().manual_seed(7)
    xs = torch.randn(N_ONE_STEP, nx, generator=g, dtype=cfg.dtype_pt)
    ks = np.linspace(K0, N - 2, N_ONE_STEP).astype(int)
    xc_res = np.random.RandomState(3).randn(N_ONE_STEP, Ac.shape[0]) * 1e3
    worst = 0.0
    with torch.no_grad():
        for i, k in enumerate(ks):
            y_n = out_fn(xs[i:i + 1])[0].numpy().astype(float)
            y_phys = y_n * ystd + y0v
            # residual arm
            e_res = (yn[k] - y_n) * ystd
            u_res = u_cons[k] + (Cc @ xc_res[i] + Dc @ e_res)
            # direct arm, with the consistent controller state xc_D + xc_res
            e_dir = sig['r'][k] - y_phys
            u_dir = Cc @ (xc_D[k] + xc_res[i]) + Dc @ e_dir + sig['f'][k]
            worst = max(worst, float(np.max(np.abs(u_dir - u_res))))
    print('  ANN gain %-6.3g   worst |u_direct - u_residual| over %d states : %.3e N'
          % (gain, N_ONE_STEP, worst))
print('  (rms u_fb is %.2e N, so this is the identity at machine precision regardless of the ANN)'
      % float(np.max(rms(u_fb_D))))

# =============================================================================================
print('\n' + '=' * 104)
print('T2  GROWTH CURVE at ANN gain %.3g, against a one-eps initial-state perturbation'
      % GROWTH_GAIN)
print('=' * 104)
set_ann_gain(fs, GROWTH_GAIN)
x0 = CV.encoder_x0(fs.encoder, un, yn, K0, na, nb, na_r, nb_r, cfg.dtype_pt)
u_t = torch.as_tensor(np.ascontiguousarray(un[None, K0:N]), dtype=cfg.dtype_pt)
y_t = torch.as_tensor(np.ascontiguousarray(yn[None, K0:N]), dtype=cfg.dtype_pt)
with torch.no_grad():
    y_res, _, _ = rollout(step_fn, out_fn, u_t, y_t, x0, bank, ctrl_t)
    x0p = x0 * (1.0 + torch.finfo(cfg.dtype_pt).eps)          # CONTROL: one eps on the state
    y_ctl, _, _ = rollout(step_fn, out_fn, u_t, y_t, x0p, bank, ctrl_t)
y_res = y_res[0].numpy()
y_ctl = y_ctl[0].numpy()
y_dir = direct_rollout(step_fn, out_fn, sig['r'][K0:N], sig['f'][K0:N], x0, xc_D[K0],
                       ctrl_np, norm, cfg.dtype_pt)

gap = np.abs(y_dir - y_res).max(axis=1) * float(np.max(ystd))
ctl = np.abs(y_ctl - y_res).max(axis=1) * float(np.max(ystd))
err = np.abs(y_res - yn[K0:N]).max(axis=1) * float(np.max(ystd))
print('  %-10s %-14s %-14s %-14s' % ('step', 'direct-resid', 'eps-perturbed', 'model error'))
for k in (1, 3, 10, 30, 100, 300, 1000, 3000, 10000, len(gap) - 1):
    if k < len(gap):
        print('  %-10d %-14.3e %-14.3e %-14.3e' % (k, gap[k], ctl[k], err[k]))
print('  If the two left columns track each other, the direct-vs-residual gap IS float noise')
print('  amplified by the model, not an algebra error (which would be O(model error) at step 1).')

