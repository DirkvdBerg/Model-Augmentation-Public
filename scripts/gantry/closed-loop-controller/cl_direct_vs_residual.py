def set_ann_gain(fs, gain, seed=0):
    """Re-initialise the ANN's LAST layer so its output is nonzero and nonlinear.

    build_pipeline ships a zero-init ANN (exact zero output), so without this the 'augmented'
    model is the LPV baseline. Only the output layer is touched: the hidden tanh layers keep
    their random init, so the map is genuinely nonlinear rather than a rescaled linear one.
    """
    ann = next(m for m in fs.hfn.connected_blocks if isinstance(m, Static_ANN_Block))
    last = [m for m in ann.net.modules() if isinstance(m, torch.nn.Linear)][-1]
    g = torch.Generator().manual_seed(seed)
    with torch.no_grad():
        w = torch.randn(last.weight.shape, generator=g, dtype=last.weight.dtype)
        b = torch.randn(last.bias.shape, generator=g, dtype=last.bias.dtype)
        last.weight.copy_(w * gain / max(1.0, np.sqrt(last.weight.shape[1])))
        last.bias.copy_(b * gain * 0.1)
    return ann


def machine_controller(r_phys, y_phys, ctrl_np):
    """Filter the MACHINE's error (r - y_data) from rest. Returns (u_fb [N], xc trajectory)."""
    Ac, Bc, Cc, Dc = ctrl_np
    N = len(r_phys)
    xc = np.zeros(Ac.shape[0])
    u = np.empty((N, Cc.shape[0]))
    xs = np.empty((N, Ac.shape[0]))
    for k in range(N):
        e = r_phys[k] - y_phys[k]
        xs[k] = xc
        u[k] = Cc @ xc + Dc @ e
        xc = Ac @ xc + Bc @ e
    return u, xs


def direct_rollout(step_fn, out_fn, r_phys, f_phys, x0, xc0, ctrl_np, norm, dtype):
    """Cfb closed around the model from the REFERENCE. Controller error is r - y_model [m]."""
    Ac, Bc, Cc, Dc = ctrl_np
    ystd = np.asarray(norm.ystd).ravel()
    y0 = np.asarray(norm.y0).ravel()
    u_mean = np.asarray(norm.u_mean).ravel()
    std_u = np.asarray(norm.std_u).ravel()
    x = x0
    xc = np.asarray(xc0, float).copy()
    ys = []
    with torch.no_grad():
        for k in range(len(r_phys)):
            y_n = out_fn(x)
            ys.append(y_n)
            e = r_phys[k] - (y_n[0].numpy().astype(float) * ystd + y0)
            u_phys = Cc @ xc + Dc @ e + f_phys[k]
            u_n = (u_phys - u_mean) / std_u
            x = step_fn(x, torch.as_tensor(u_n[None, :], dtype=dtype))
            xc = Ac @ xc + Bc @ e
    return torch.cat(ys, dim=0).numpy()


