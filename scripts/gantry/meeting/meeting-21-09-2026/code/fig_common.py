# =================================================================================================
# Finding the settling windows
# =================================================================================================

def move_edges(r, tol=0.0):
    """(starts, stops) sample indices of every setpoint MOVE in a decimated reference `r`.

    A sample is "moving" if the reference changes between it and the next. Derived from `r_sim`
    rather than from `y`, because `y` never stops moving: the absorber rings through the dwell,
    which is the entire point of the figure.
    """
    r = np.asarray(r, dtype=np.float64)
    moving = (np.abs(np.diff(r, axis=0)) > tol).any(axis=1)
    edges = np.diff(np.concatenate([[0], moving.astype(int), [0]]))
    return np.flatnonzero(edges == 1), np.flatnonzero(edges == -1)


def settling_windows(r, min_dwell_s=0.30):
    """Every (move_end, dwell_end) pair with at least `min_dwell_s` of dwell after it.

    These are the settling events. A move whose travel is zero is dropped: the APRBS draw can
    land on the current setpoint, and a no-op move is not a settling event.
    """
    starts, stops = move_edges(r)
    travel = np.array([np.abs(r[min(e, len(r) - 1)] - r[s]).max() for s, e in zip(starts, stops)])
    n_min = int(round(min_dwell_s * FS))
    out = []
    for j, (s, e) in enumerate(zip(starts, stops)):
        nxt = starts[j + 1] if j + 1 < len(starts) else len(r)
        if travel[j] > 0 and (nxt - e) >= n_min:
            out.append((int(e), int(nxt), float(travel[j])))
    return out


def pick_window(r, dur_s=0.40):
    """The settling window to zoom on: the dwell after the LARGEST move.

    Picked from the data, not by hand, so the same rule applies to every arm and to any record
    this code is later pointed at. The largest move is the one that rings the 212.13 Hz mode
    hardest, which is where the arms have the best chance of separating.
    """
    w = settling_windows(r)
    if not w:
        raise SystemExit('no settling window with enough dwell in this record')
    e, nxt, _ = max(w, key=lambda x: x[2])
    n = int(round(dur_s * FS))
    return int(e), int(min(e + n, nxt, len(r)))


