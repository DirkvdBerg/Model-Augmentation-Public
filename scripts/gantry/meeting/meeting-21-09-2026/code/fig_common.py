def sci_axis(ax):
    """Scientific notation with an explicit 1e-N offset. The display contract's first line."""
    ax.ticklabel_format(axis='y', style='sci', scilimits=(0, 0), useMathText=True)
    ax.yaxis.get_offset_text().set_fontsize(7)
    ax.yaxis.get_offset_text().set_color(MUTED)


def two_col_axes(plt, nrows, figsize):
    """A (nrows, 2) grid: the FULL record on the left, the settling zoom on the right.

    The columns do NOT share a y-axis. The setpoint travel is 1e-01 m and what happens during a
    dwell is 1e-05 m, so a shared scale renders the zoom as a flat line and shows nothing at all.
    Each column carries its own tick labels, so the second scale is stated rather than silent.
    """
    fig, axes = plt.subplots(nrows, 2, figsize=figsize, squeeze=False,
                             gridspec_kw={'width_ratios': [2.1, 1]})
    for r in range(1, nrows):
        for c in (0, 1):
            axes[r][c].sharex(axes[0][c])
    return fig, axes


def finish_columns(axes, t_full, twin, zoom_note=''):
    """x-limits and x-labels for a `two_col_axes` grid. Call once, after all the plotting."""
    axes[0][0].set_xlim(float(t_full[0]), float(t_full[-1]))
    axes[0][1].set_xlim(*twin)
    for r in range(len(axes) - 1):
        for c in (0, 1):
            axes[r][c].tick_params(labelbottom=False)
    axes[-1][0].set_xlabel('time [s]')
    axes[-1][1].set_xlabel('time [s]')
    title = '%.2f to %.2f s' % twin
    if zoom_note:
        title += '   %s' % zoom_note
    axes[0][1].set_title(title, fontsize=8, color=MUTED, pad=4)


def load_cache():
    p = cache_path()
    if not p.exists():
        raise SystemExit(
            'no cache at %s. Run `python collect.py` first: it is the only script here that '
            'simulates, and every figure then redraws from it in a second.' % p)
    return dict(np.load(p, allow_pickle=True))
