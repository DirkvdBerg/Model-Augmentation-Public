"""Shared constants, palette and axis helpers for the 2026-09-21 settling figures.

No plotting and no simulation live here: this is what `collect.py` and `fig_settling.py` must
AGREE on, and nothing else.

WHAT THESE FIGURES ARE FOR. Quinten, meeting 2026-09-18: "Plaatje inzoomt op settling", and
crucially "Voor het model vooral het gedrag van hoe die settled, system afhankelijk niet het
model". The settling itself is a property of the plant and its controller, not of the model, so
these figures do NOT report a settling time and do NOT draw a tolerance band. They show the
BEHAVIOUR of each model during the settling window, against the data, and let the arms be
compared to each other. That is also why no epsilon is defined anywhere in this folder: the data
is noiseless (`SNR = None`), so there is no noise floor to derive one from, and a hand-picked
band would decide the figure by itself.

THE RECORD is `S1_settle_Ylow_noexc`, generated by
`Matlab-scripts/Augmentation-settling/data/generate_trajectory_data_settling.m` (D-205). It is
the validation jerk-limited profile with the injected multisine OFF and a 0.4 s dwell between
moves. The multisine had to be removed at GENERATION time, not afterwards: `gtd_run_simulation.m`
forms `u_fb = lsim(Cfb, r_sim - q_with)` against the output with the multisine acting, so the
controller responded to it and `u_fb` carries a multisine-induced component of its own.

MEASURED, and the reason to read the zoom panels with care: this record's absorber deflection is
`rms 5.95e-06 m`, against `4.50e-05 m` on V2 (multisine on) and `1.63e-05 m` on E4. With the
excitation off, the 212.13 Hz coupled mode is driven only by the jerk transients. If the arms
draw on top of each other in the zoom, that is a statement about excitation, not a broken figure.

NAMING, carried over from the 2026-09-07 set because the same two traps apply.

`y` is NOT a measurement. `SNR: null`, so it is the noiseless output of the MATLAB simulation of
the extended plant, the FP model plus the hidden mass-spring-damper absorber, decimated to 4 kHz.
It is called "system" on every figure, never "measured".

`y_hat` is NOT a free run. The loop is

    y_hat[k]      = C x[k]
    u_fb[k], xc   = Cfb(xc, y_data[k] - y_hat[k])
    x[k+1]        = f(x[k], u_data[k] + u_fb[k])

so the recorded output enters through the controller at EVERY timestep. What is free is the model
STATE: x is propagated by the model and never teacher-forced, and x_0 comes from the encoder
window alone. Every arm, the baseline included, runs this identical loop; the ONLY difference
between arms is the ANN. Panels say "closed loop" so the ambiguity is never silent.

Layout:
    fig_common.py    this file: paths, arms, palette, axis helpers
    build.py         checkpoint -> closed-loop system (the only file that touches torch weights)
    collect.py       the only file that simulates; writes settling_data.npz
    fig_settling.py  redraws the five figures from the cache in a second
"""
