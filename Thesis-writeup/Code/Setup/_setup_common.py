"""Shared helpers for the Section V (Experiment design) number scripts.

Every script reads only the thesis dataset named on its command line (default: the dataset of the
reported runs, Coulomb-tanh-and-MSD-lowpass-noise, runs.tsv rows 201 to 207, D-238) and its
noise-free twin, writes Thesis-writeup/Results/setup_<name>.csv, and registers its LaTeX macros.
All macros live in Thesis-writeup/Results/setup_numbers.json and are rendered together into
Thesis-writeup/Writing/tables/setup_numbers.tex, so the text never retypes a number.
"""
import csv
import json
import os
import sys

import numpy as np
from scipy.io import loadmat

HERE = os.path.dirname(os.path.abspath(__file__))                 # Thesis-writeup/Code/Setup
TW = os.path.abspath(os.path.join(HERE, '..', '..'))              # Thesis-writeup
REPO = os.path.dirname(TW)
DATA = os.path.join(TW, 'Data')
RESULTS = os.path.join(TW, 'Results')
MACRO_JSON = os.path.join(RESULTS, 'setup_numbers.json')
MACRO_TEX = os.path.join(TW, 'Writing', 'tables', 'setup_numbers.tex')

DEFAULT_DATASET = 'Coulomb-tanh-and-MSD-lowpass-noise'
NOISE_FREE = 'Coulomb-tanh-and-MSD-noise-free'
AXES = ('X1', 'X2', 'Y')                                          # stage axes, column order of y, r, u
AXIS_TAG = {'X1': 'Xone', 'X2': 'Xtwo', 'Y': 'Y'}                 # LaTeX macro names take no digits
SPLIT_DIR = {'training': 'Training', 'validation': 'Validation', 'test-I': 'Test', 'test-E': 'Test'}


def dataset_arg():
    """Dataset folder name from argv[1], else the dataset of the reported runs."""
    return sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DATASET


def manifest(dataset, blocks=('training', 'validation', 'test-I', 'test-E')):
    """Rows of the dataset's MANIFEST.csv in the given blocks (the TF FRF references are not records)."""
    with open(os.path.join(DATA, dataset, 'MANIFEST.csv'), newline='') as fh:
        rows = [r for r in csv.DictReader(fh) if r['block'] in blocks]
    return rows


def record_path(dataset, row):
    return os.path.join(DATA, dataset, SPLIT_DIR[row['block']], row['file'] + '.mat')


def load(path, fields=None):
    """One record; fields limits what is read (each record holds about 50 MB)."""
    return loadmat(path, squeeze_me=True, struct_as_record=False, variable_names=fields)


def truth_params(dataset):
    """meta.truth of the first training record: the simulated parameter values (generate_thesis_data.m)."""
    row = manifest(dataset, ('training',))[0]
    t = load(record_path(dataset, row), ['meta'])['meta'].truth
    return {f: getattr(t, f) for f in t._fieldnames}


def rms(x, axis=0):
    return np.sqrt(np.mean(np.asarray(x, dtype=np.float64) ** 2, axis=axis))


def write_csv(name, header, rows):
    os.makedirs(RESULTS, exist_ok=True)
    path = os.path.join(RESULTS, 'setup_%s.csv' % name)
    with open(path, 'w', newline='') as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    print('wrote', path)


def set_macros(script, macros):
    """Register this script's macros {name: (latex value, comment)} and re-render setup_numbers.tex."""
    os.makedirs(RESULTS, exist_ok=True)
    store = {}
    if os.path.isfile(MACRO_JSON):
        with open(MACRO_JSON) as fh:
            store = json.load(fh)
    store[script] = {k: list(v) for k, v in macros.items()}
    with open(MACRO_JSON, 'w') as fh:
        json.dump(store, fh, indent=1, sort_keys=True)
    lines = ['% GENERATED by Thesis-writeup/Code/Setup/*.py (see its README); never edit by hand.',
             '% Section V (Experiment design) numbers computed on the thesis dataset.']
    for s in sorted(store):
        lines.append('%% --- %s.py' % s)
        for name in sorted(store[s]):
            value, comment = store[s][name]
            lines.append('\\providecommand{\\%s}{}\\renewcommand{\\%s}{%s}%% %s' % (name, name, value, comment))
    with open(MACRO_TEX, 'w', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', MACRO_TEX)
    for name in sorted(macros):
        print('  \\%s = %s   (%s)' % (name, macros[name][0], macros[name][1]))


# ── linear models from meta.truth (simulation-only design information, Section V-B) ────────────

def P_matrix(T):
    Lb = T['Lb']
    return np.array([[1., 1., 0.], [Lb / 2, -Lb / 2, 0.], [0., 0., 1.]])


def CK_logical(T):
    """Damping and stiffness of eq:damping_stiffness_matrices (logical coordinates X, Theta, Y)."""
    Lb = T['Lb']
    C = np.array([[T['cg1'] + T['cg2'], (T['cg1'] - T['cg2']) * Lb / 2, 0.],
                  [(T['cg1'] - T['cg2']) * Lb / 2, T['cb1'] + T['cb2'] + (T['cg1'] + T['cg2']) * Lb ** 2 / 4, 0.],
                  [0., 0., T['cy']]])
    K = np.diag([0., T['kb1'] + T['kb2'], 0.])
    return C, K


def M_rigid(T, Y):
    """eq:mass_matrix with the total head mass m_h (the baseline; gtd_build_plant.m rigid_plant)."""
    m1, m2, mb, mh, Lb, d = T['m1'], T['m2'], T['mb'], T['mh'], T['Lb'], T['d']
    return np.array([[m1 + m2 + mb + mh, (m1 - m2) * Lb / 2 - mh * Y, 0.],
                     [(m1 - m2) * Lb / 2 - mh * Y, T['Jb'] + T['Jh'] + (m1 + m2) * Lb ** 2 / 4 + mh * (d ** 2 + Y ** 2), -mh * d],
                     [0., -mh * d, mh]])


def M_truth(T, Y, da=0.0):
    """M_e(Y, delta_a) of eq:setup_truth (gantrySystemExtendedTanh.m, called with mh = mh_rigid)."""
    ma, l, d = T['ma'], T['L0'] + da, T['d']
    E = np.array([[0., -l, 0.], [-l, l * (2 * Y + l), 0.], [0., 0., 0.]])
    e = np.array([0., -d, 1.])
    M = np.zeros((4, 4))
    M[:3, :3] = M_rigid(T, Y) + ma * E
    M[:3, 3] = M[3, :3] = ma * e
    M[3, 3] = ma
    return M


def frf_stage(T, Y, f, truth=True):
    """G(j 2 pi f): stage force -> stage position, (n_f, 3, 3); truth = absorber on, friction off
    (tdg_truth_lin.m with g = 0), else the rigid baseline."""
    P = P_matrix(T)
    C, K = CK_logical(T)
    if truth:
        M = M_truth(T, Y)
        Ce = np.zeros((4, 4)); Ce[:3, :3] = C; Ce[3, 3] = T['ca']
        Ke = np.zeros((4, 4)); Ke[:3, :3] = K; Ke[3, 3] = T['ka']
        Bin = np.vstack([P, np.zeros((1, 3))]); Cout = np.hstack([P.T, np.zeros((3, 1))])
        M, C, K = M, Ce, Ke
    else:
        M = M_rigid(T, Y); Bin = P; Cout = P.T
    out = np.empty((len(f), 3, 3), dtype=complex)
    for i, fi in enumerate(np.atleast_1d(f)):
        s = 2j * np.pi * fi
        out[i] = Cout @ np.linalg.solve(M * s ** 2 + C * s + K, Bin)
    return out


def k1_continuous(T, fbw=100.0, design_Y=0.0):
    """K1 per stage axis, eq:setup_K1 (vendor/ruleOfThumb.m): returns (num, den, kappa[3]).
    # THEORY: ruleOfThumb.m: Cnorm = (s + wb/6)/s * (s + wb/3)/(s + 3 wb) * 10 wb/(s + 10 wb),
    #         kappa_j = 1 / |G_jj(j wb) Cnorm(j wb)| on the rigid baseline at design_Y."""
    wb = 2 * np.pi * fbw
    num = np.polymul(np.polymul([1., wb / 6], [1., wb / 3]), [10 * wb])
    den = np.polymul(np.polymul([1., 0.], [1., 3 * wb]), [1., 10 * wb])
    G = frf_stage(T, design_Y, [fbw], truth=False)[0]
    cw = np.polyval(num, 1j * wb) / np.polyval(den, 1j * wb)
    kappa = np.array([1.0 / abs(G[j, j] * cw) for j in range(3)])
    return num, den, kappa


def sci(x, digits=1):
    """Scientific notation for metres in the text, e.g. 3.2\\cdot10^{-9} (errors always scientific)."""
    m, e = ('%.*e' % (digits, x)).split('e')
    return '%s\\cdot10^{%d}' % (m, int(e))
